let errors = 0;
for (const [key, matrix] of Object.entries({...cropMatrices, ...fishMatrices})) {
  if (matrix.length !== 16) {
    console.error(`Error: ${key} has ${matrix.length} rows instead of 16`);
    errors++;
  }
  matrix.forEach((row, i) => {
    if (row.length !== 16) {
      console.error(`Error: ${key} row ${i} has length ${row.length} instead of 16`);
      errors++;
    }
  });
}

if (errors === 0) {
  console.log('SUCCESS: All 31 matrices verified to be exactly 16x16!');
} else {
  console.log(`FAILED: Found ${errors} matrix errors.`);
}
